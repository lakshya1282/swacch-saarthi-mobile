#!/usr/bin/env node
/**
 * Integration Test Script for Mobile App <-> Dashboard Communication
 * Tests all three integration points:
 * 1. Worker Enrollment System
 * 2. QR Code Attendance
 * 3. Pickup Assignment Flow
 */

const axios = require('axios');
const io = require('socket.io-client');
const colors = require('colors');

const API_URL = 'http://localhost:3000/api';
const SOCKET_URL = 'http://localhost:3000';

// Test data
const testOfficeCode = 'ECO' + Date.now().toString(36).toUpperCase();
const testWorker = {
  firstName: 'Test',
  lastName: 'Worker',
  email: `worker${Date.now()}@test.com`,
  phone: '+91 9876543210',
  password: 'test123'
};

const testCitizen = {
  firstName: 'Test',
  lastName: 'Citizen',
  email: `citizen${Date.now()}@test.com`,
  phone: '+91 9876543211',
  password: 'test123'
};

// Helper functions
function log(message, type = 'info') {
  const prefix = {
    success: '✅',
    error: '❌',
    info: 'ℹ️',
    warning: '⚠️',
    test: '🧪'
  };
  
  const colorFn = {
    success: colors.green,
    error: colors.red,
    info: colors.blue,
    warning: colors.yellow,
    test: colors.cyan
  };
  
  console.log(colorFn[type](`${prefix[type]} ${message}`));
}

function delay(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

// Test functions
async function testWorkerEnrollment() {
  log('Testing Worker Enrollment System...', 'test');
  
  try {
    // 1. Create test office (simulating dashboard registration)
    log('Creating test office...', 'info');
    const officeData = {
      officeName: 'Test Office',
      officeCode: testOfficeCode,
      address: {
        street: 'Test Street',
        city: 'Test City',
        state: 'Test State',
        pincode: '123456'
      }
    };
    
    // 2. Register worker (mobile app)
    log('Registering worker...', 'info');
    const workerRegResponse = await axios.post(`${API_URL}/auth/register`, {
      ...testWorker,
      userType: 'worker'
    });
    
    if (!workerRegResponse.data.success) {
      throw new Error('Worker registration failed');
    }
    
    const workerToken = workerRegResponse.data.token;
    log('Worker registered successfully', 'success');
    
    // 3. Worker enrolls in office (mobile app)
    log(`Worker enrolling with office code: ${testOfficeCode}`, 'info');
    const enrollResponse = await axios.post(
      `${API_URL}/worker/enroll-in-office`,
      { 
        workerId: workerRegResponse.data.user._id,
        officeCode: testOfficeCode 
      },
      {
        headers: { Authorization: `Bearer ${workerToken}` }
      }
    );
    
    if (enrollResponse.data.success) {
      log('Worker enrolled successfully!', 'success');
      
      // 4. Connect socket as dashboard to receive notification
      const dashboardSocket = io(SOCKET_URL);
      
      dashboardSocket.on('connect', () => {
        dashboardSocket.emit('dashboard-connect', {
          officeCode: testOfficeCode,
          operatorId: 'test-operator'
        });
      });
      
      dashboardSocket.on('new-worker-enrolled', (data) => {
        log(`Dashboard received enrollment notification: ${data.workerName}`, 'success');
        dashboardSocket.disconnect();
      });
      
      // 5. Connect socket as worker to notify enrollment
      const workerSocket = io(SOCKET_URL);
      
      workerSocket.on('connect', () => {
        workerSocket.emit('worker-enrolled', {
          workerId: workerRegResponse.data.user._id,
          workerName: `${testWorker.firstName} ${testWorker.lastName}`,
          officeCode: testOfficeCode
        });
        
        setTimeout(() => {
          workerSocket.disconnect();
        }, 1000);
      });
      
      await delay(2000);
      log('Worker Enrollment Test PASSED ✅', 'success');
      return true;
    }
  } catch (error) {
    log(`Worker Enrollment Test FAILED: ${error.message}`, 'error');
    return false;
  }
}

async function testQRCodeAttendance() {
  log('Testing QR Code Attendance System...', 'test');
  
  try {
    // 1. Dashboard generates QR code data
    const qrData = {
      type: 'attendance',
      officeCode: testOfficeCode,
      attendanceCode: `ATT-${testOfficeCode}`,
      timestamp: Date.now()
    };
    
    log('QR code generated by dashboard', 'info');
    log(`QR Data: ${JSON.stringify(qrData)}`, 'info');
    
    // 2. Worker scans QR (mobile app simulation)
    const dashboardSocket = io(SOCKET_URL);
    const workerSocket = io(SOCKET_URL);
    
    // Setup dashboard listener
    dashboardSocket.on('connect', () => {
      dashboardSocket.emit('dashboard-connect', {
        officeCode: testOfficeCode,
        operatorId: 'test-operator'
      });
    });
    
    dashboardSocket.on('worker-attendance-update', (data) => {
      log(`Dashboard received attendance: ${data.workerName} ${data.action}`, 'success');
      dashboardSocket.disconnect();
      workerSocket.disconnect();
    });
    
    // Worker marks attendance
    workerSocket.on('connect', () => {
      log('Worker scanning QR code...', 'info');
      
      // Simulate QR scan and attendance marking
      workerSocket.emit('attendance-marked', {
        workerId: 'test-worker-id',
        workerName: 'Test Worker',
        officeCode: testOfficeCode,
        action: 'check_in',
        time: new Date().toISOString(),
        location: { latitude: 12.9716, longitude: 77.5946 }
      });
    });
    
    await delay(2000);
    log('QR Code Attendance Test PASSED ✅', 'success');
    return true;
  } catch (error) {
    log(`QR Code Attendance Test FAILED: ${error.message}`, 'error');
    return false;
  }
}

async function testPickupAssignmentFlow() {
  log('Testing Pickup Assignment Flow...', 'test');
  
  try {
    const pickupId = `PU${Date.now()}`;
    
    // Setup sockets
    const citizenSocket = io(SOCKET_URL);
    const dashboardSocket = io(SOCKET_URL);
    const workerSocket = io(SOCKET_URL);
    
    // 1. Dashboard connects
    dashboardSocket.on('connect', () => {
      dashboardSocket.emit('dashboard-connect', {
        officeCode: testOfficeCode,
        operatorId: 'test-operator'
      });
    });
    
    // 2. Dashboard receives new pickup request
    dashboardSocket.on('new-pickup-request', (data) => {
      log(`Dashboard received pickup request: ${data.pickupId}`, 'success');
    });
    
    // 3. Dashboard receives assignment update
    dashboardSocket.on('pickup-assignment-update', (data) => {
      log(`Dashboard: Pickup ${data.pickupId} assigned to ${data.workerName}`, 'success');
    });
    
    // 4. Dashboard receives completion notification
    dashboardSocket.on('pickup-completed', (data) => {
      log(`Dashboard: Pickup completed! Weight: ${data.actualWeight}kg, Incentive: ₹${data.incentiveEarned}`, 'success');
      
      // Cleanup
      citizenSocket.disconnect();
      dashboardSocket.disconnect();
      workerSocket.disconnect();
    });
    
    // 5. Worker connects
    workerSocket.on('connect', () => {
      workerSocket.emit('worker-enrolled', {
        workerId: 'test-worker-id',
        workerName: 'Test Worker',
        officeCode: testOfficeCode
      });
    });
    
    // 6. Worker receives stats update
    workerSocket.on('stats-update', (data) => {
      log(`Worker stats updated: Incentive earned: ₹${data.incentiveEarned}`, 'info');
    });
    
    // 7. Citizen schedules pickup
    await delay(1000);
    log('Citizen scheduling pickup...', 'info');
    
    citizenSocket.on('connect', () => {
      citizenSocket.emit('pickup-scheduled', {
        pickupId: pickupId,
        citizenId: 'test-citizen-id',
        location: { latitude: 12.9716, longitude: 77.5946 },
        wasteTypes: ['Dry Waste', 'Wet Waste'],
        scheduledTime: '10:00 AM - 2:00 PM'
      });
    });
    
    // 8. Worker accepts pickup
    await delay(1000);
    log('Worker accepting pickup...', 'info');
    
    workerSocket.emit('pickup-accepted', {
      pickupId: pickupId,
      citizenId: 'test-citizen-id',
      workerId: 'test-worker-id',
      workerName: 'Test Worker',
      officeCode: testOfficeCode,
      estimatedArrival: '30 minutes'
    });
    
    // 9. Worker starts pickup
    await delay(1000);
    log('Worker starting pickup...', 'info');
    
    workerSocket.emit('pickup-started', {
      pickupId: pickupId,
      workerId: 'test-worker-id',
      officeCode: testOfficeCode,
      location: { latitude: 12.9716, longitude: 77.5946 }
    });
    
    // 10. Worker completes pickup with QR verification
    await delay(1000);
    log('Worker completing pickup with QR verification...', 'info');
    
    workerSocket.emit('pickup-completed', {
      pickupId: pickupId,
      workerId: 'test-worker-id',
      officeCode: testOfficeCode,
      qrVerified: true,
      actualWeight: 20, // 20kg - will trigger incentive
      completionPhoto: 'base64_photo_data'
    });
    
    await delay(2000);
    log('Pickup Assignment Flow Test PASSED ✅', 'success');
    return true;
  } catch (error) {
    log(`Pickup Assignment Flow Test FAILED: ${error.message}`, 'error');
    return false;
  }
}

// Main test runner
async function runIntegrationTests() {
  console.log('\n' + colors.rainbow('='.repeat(60)));
  console.log(colors.bold.cyan('🧪 WASTE MANAGEMENT INTEGRATION TEST SUITE 🧪'));
  console.log(colors.rainbow('='.repeat(60)) + '\n');
  
  log('Starting integration tests...', 'info');
  log('Make sure server is running on http://localhost:3000', 'warning');
  
  await delay(2000);
  
  const results = {
    workerEnrollment: false,
    qrCodeAttendance: false,
    pickupAssignment: false
  };
  
  // Run tests
  console.log('\n' + colors.yellow('─'.repeat(60)) + '\n');
  results.workerEnrollment = await testWorkerEnrollment();
  
  console.log('\n' + colors.yellow('─'.repeat(60)) + '\n');
  results.qrCodeAttendance = await testQRCodeAttendance();
  
  console.log('\n' + colors.yellow('─'.repeat(60)) + '\n');
  results.pickupAssignment = await testPickupAssignmentFlow();
  
  // Summary
  console.log('\n' + colors.rainbow('='.repeat(60)));
  console.log(colors.bold.cyan('📊 TEST RESULTS SUMMARY 📊'));
  console.log(colors.rainbow('='.repeat(60)) + '\n');
  
  const passed = Object.values(results).filter(r => r).length;
  const failed = Object.values(results).filter(r => !r).length;
  
  console.log(colors.green(`✅ Passed: ${passed}`));
  console.log(colors.red(`❌ Failed: ${failed}`));
  
  if (failed === 0) {
    console.log('\n' + colors.green.bold('🎉 ALL INTEGRATION TESTS PASSED! 🎉'));
    console.log(colors.green('The mobile app and dashboard are properly integrated!'));
  } else {
    console.log('\n' + colors.red.bold('⚠️ SOME TESTS FAILED ⚠️'));
    console.log(colors.yellow('Please check the error messages above and fix the issues.'));
  }
  
  console.log('\n' + colors.rainbow('='.repeat(60)) + '\n');
  
  process.exit(failed === 0 ? 0 : 1);
}

// Run tests
runIntegrationTests().catch(error => {
  log(`Fatal error: ${error.message}`, 'error');
  process.exit(1);
});